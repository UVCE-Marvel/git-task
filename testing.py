_DATA = json.loads(
    zlib.decompress(base64.b64decode(_DATA_BLOB.encode("ascii"))).decode("utf-8")
)
ORACLE = _DATA["oracle"]
MODULES = _DATA["modules"]
ASSIGNMENTS = _DATA["assignments"]


def get_user_assignment(username: str) -> list:
    """
    Deterministically assign 5 functions for `username` across 5 distinct
    scenario modules using a SHA-256 digest of the GitHub handle.
    """
    clean = username.strip().lower().lstrip("@")
    digest = hashlib.sha256(f"uvce-marvel-v2:{clean}".encode("utf-8")).hexdigest()
    idx = int(digest, 16) % len(ASSIGNMENTS)
    return [
        {
            "module": ORACLE[fname]["module"],
            "function": fname,
        }
        for fname in ASSIGNMENTS[idx]
    ]


def detect_modified_functions() -> list:
    """Return list of function names whose code fingerprint differs from initial state."""
    modified = []
    for mod_name in MODULES:
        mod_path = os.path.join(REPO_DIR, f"{mod_name}.py")
        if not os.path.exists(mod_path):
            continue
        with open(mod_path, "r", encoding="utf-8") as f:
            curr_prints = function_fingerprints(f.read())
        for fname, curr_fp in curr_prints.items():
            spec = ORACLE.get(fname)
            if spec and spec["fingerprint"] != curr_fp:
                modified.append(fname)
    return modified


def verify_function(fname: str):
    """Run test cases for `fname` and assert its outputs match the target digest."""
    spec = ORACLE[fname]
    mod = importlib.import_module(spec["module"])
    importlib.reload(mod)
    fn = getattr(mod, fname)
    cases, report = _run_cases(fn, fname, spec["inputs"])
    digest = _digest(fname, cases)
    if digest != spec["target"]:
        preview = "\n    ".join(report)
        raise AssertionError(
            f"Function '{spec['module']}.{fname}' did not pass verification.\n"
            f"  Your function produced:\n    {preview}\n"
            f"  Re-read the docstring of '{fname}' in {spec['module']}.py and check every rule."
        )


if pytest is not None:
    @pytest.mark.parametrize("fname", detect_modified_functions() or ["__none__"])
    def test_modified_functions(fname: str):
        """Verify every function modified by the contributor."""
        if fname == "__none__":
            pytest.fail(
                "No modified functions detected across the scenario modules. "
                "Run `python my_task.py <your-github-username>` to see your 5 assigned functions."
            )
        verify_function(fname)
