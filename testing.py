def _canon(value):
    """Convert a value into a stable, JSON-friendly form for hashing."""
    if value is None or isinstance(value, (bool, str)):
        return value
    if isinstance(value, (int, float)):
        return round(float(value), 6) + 0.0
    if isinstance(value, (list, tuple)):
        return [_canon(item) for item in value]
    if isinstance(value, (set, frozenset)):
        return sorted((_canon(item) for item in value), key=repr)
    if isinstance(value, dict):
        pairs = sorted(value.items(), key=lambda pair: repr(pair[0]))
        return [[_canon(key), _canon(item)] for key, item in pairs]
    return "<" + type(value).__name__ + ">"


def _digest(fname, cases):
    payload = fname + ":" + json.dumps(cases, sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _run_cases(fn, fname, inputs):
    """Call fn on every input. Return (canonical cases, readable report lines)."""
    cases = []
    report = []
    for args in inputs:
        call_args = copy.deepcopy(args)
        try:
            raw = fn(*call_args)
            shown = repr(raw)
            result = _canon(raw)
        except Exception as exc:  # noqa: BLE001 - student code may raise anything
            shown = "raised " + type(exc).__name__
            result = ["__raised__", type(exc).__name__]
        cases.append([result, _canon(call_args)])
        line = fname + "(" + ", ".join(repr(arg) for arg in args) + ") -> " + shown
        if call_args != args:
            line += "   [input list/dict was modified in place]"
        report.append(line)
    return cases, report


def function_fingerprints(source):
    """Fingerprint each top-level function, ignoring docstrings, comments and blank lines."""
    tree = ast.parse(source)
    lines = source.splitlines()
    prints = {}
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef):
            continue
        skip = set()
        first = node.body[0] if node.body else None
        if (
            isinstance(first, ast.Expr)
            and isinstance(first.value, ast.Constant)
            and isinstance(first.value.value, str)
        ):
            skip = set(range(first.lineno, first.end_lineno + 1))
        kept = []
        for number in range(node.lineno, node.end_lineno + 1):
            if number in skip:
                continue
            text = lines[number - 1].rstrip()
            if not text.strip() or text.strip().startswith("#"):
                continue
            kept.append(text)
        prints[node.name] = hashlib.sha256("\n".join(kept).encode("utf-8")).hexdigest()
    return prints

